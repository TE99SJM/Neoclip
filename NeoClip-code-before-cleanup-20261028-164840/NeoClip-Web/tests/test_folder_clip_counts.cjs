const {readFileSync} = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const html = readFileSync(`${__dirname}/../app/web/index.html`, 'utf8');
const ctx = {libraryClipCounts: {'Games/one.mp4':5, 'Games/Sub/two.mp4':1, 'Other/no.mp4':0, 'top.mp4':3}};
vm.createContext(ctx);
vm.runInContext(html.slice(html.indexOf('    function folderEntries('), html.indexOf('    function openFolder(')), ctx);
const files = ['Games/one.mp4','Games/Sub/two.mp4','Games/Sub/three.mp4','Other/no.mp4','top.mp4'].map(path=>({path,name:path.split('/').pop()}));
let result = ctx.folderEntries(files, '');
assert.equal(result.folders[0].name, 'Games');
assert.equal(result.folders[0].count, 3);
assert.equal(result.folders[0].videosWithClips, 2, 'count videos, not five individual clips');
assert.equal(result.folders[1].videosWithClips, 0);
result = ctx.folderEntries(files, 'Games');
assert.equal(result.folders[0].videosWithClips, 1, 'nested folder counts only descendants');
ctx.libraryClipCounts = {};
assert.equal(ctx.folderEntries(files, '').folders[0].videosWithClips, 0, 'render/removal updates the count');
assert.match(html, /\$\{folder.videosWithClips\} with clips/);
console.log('Folder counts include descendants and count each queued video once');
